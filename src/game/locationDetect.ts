const cosA = Math.cos(angle);
const sinA = Math.sin(angle);

/**
 * World (x, z) သြဒိနိတ်မှ AH1 လမ်းမကြီးအလိုက် Local (u, v) သြဒိနိတ်သို့ ပြောင်းလဲပေးသော function
 * u: အနောက် (-) မှ အရှေ့ (+)
 * v: မြောက် (-) မှ တောင် (+)
 */
export function toLocalUV(x: number, z: number): { u: number; v: number } {
  return {
    u: x * cosA - z * sinA,
    v: x * sinA + z * cosA,
  };
}

